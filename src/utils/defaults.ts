type SeedRow = [name: string, days: number, pin?: number];

function buildSeedMembers(rows: SeedRow[], capacity: number): GroupMember[] {
  return rows.map(([n, d, pin], idx) => {
    const info = getMemberTracking({ n, d, totalPaid: d, rounds: [] }, capacity);
    return {
      n,
      d: info.activeDays,
      totalPaid: info.totalPaid,
      rounds: info.rounds,
      mod: idx === 0,
      pin: Boolean(pin),
    };
  });
}

function makeGroups(
  caps: readonly number[],
  seed?: Record<number, SeedRow[]>
): ProductGroup[] {
  const raw: ProductGroup[] = caps.map((c, i) => {
    const r = seed && seed[i] ? buildSeedMembers(seed[i], c) : [];
    return {
      n: GROUP_LETTERS[i],
      c,
      r,
      j: r.length,
      rot: 1,
    };
  });
  return enforceProductGroups(raw);
}

